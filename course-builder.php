/** Statuses the builder shows and edits. Trash and auto-drafts stay out. */
function snn_builder_statuses() {
    return [ 'publish', 'draft', 'pending', 'private', 'future' ];
}

/** The statuses an author may set from the builder. */
function snn_builder_settable_statuses() {
    return [ 'publish', 'draft', 'pending', 'private' ];
}

function snn_builder_can_manage() {
    $pt = get_post_type_object( snn_learn_course_pt() );
    return $pt ? current_user_can( $pt->cap->edit_others_posts ) : current_user_can( 'edit_others_posts' );
}

function snn_builder_error( $code, $message, $status = 400 ) {
    return new WP_Error( $code, $message, [ 'status' => $status ] );
}

/** A course post by id, or a WP_Error. $role limits which role is accepted. */
function snn_builder_get( $id, $role = '' ) {
    $post = get_post( (int) $id );
    if ( ! $post || $post->post_type !== snn_learn_course_pt() || ! in_array( $post->post_status, snn_builder_statuses(), true ) ) {
        return snn_builder_error( 'snn_builder_not_found', 'That item does not exist or is in the trash.', 404 );
    }
    if ( $role && snn_learn_post_role( $post ) !== $role ) {
        return snn_builder_error( 'snn_builder_wrong_role', sprintf( 'That item is not a %s.', $role ) );
    }
    if ( ! current_user_can( 'edit_post', $post->ID ) ) {
        return snn_builder_error( 'snn_builder_forbidden', 'You cannot edit that item.', 403 );
    }
    return $post;
}

/** Direct children of a post, in builder order. */
function snn_builder_children( $parent_ids ) {
    $parent_ids = array_filter( array_map( 'intval', (array) $parent_ids ) );
    if ( ! $parent_ids ) {
        return [];
    }

    return get_posts( [
        'post_type'              => snn_learn_course_pt(),
        'post_parent__in'        => $parent_ids,
        'post_status'            => snn_builder_statuses(),
        'posts_per_page'         => -1,
        'orderby'                => [ 'menu_order' => 'ASC', 'ID' => 'ASC' ],
        'suppress_filters'       => true,
        'update_post_term_cache' => false,
    ] );
}

function snn_builder_next_order( $parent_id ) {
    global $wpdb;
    $max = $wpdb->get_var( $wpdb->prepare(
        "SELECT MAX(menu_order) FROM {$wpdb->posts} WHERE post_parent = %d AND post_type = %s AND post_status NOT IN ('trash','auto-draft','inherit')",
        (int) $parent_id, snn_learn_course_pt()
    ) );
    return null === $max ? 0 : (int) $max + 1;
}

/** Fields that can be generated by AI for a lesson, for the "AI 2/3" badge. */
function snn_builder_lesson_ai_fields() {
    static $fields = null;
    if ( null === $fields ) {
        $fields = array_values( array_filter( snn_cf_get_fields(), function ( $field ) {
            return $field['ai_enabled']
                && in_array( snn_learn_course_pt(), (array) $field['post_types'], true )
                && ( ! $field['roles'] || in_array( 'lesson', $field['roles'], true ) );
        } ) );
    }
    return $fields;
}

