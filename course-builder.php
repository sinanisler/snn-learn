function snn_builder_base_node( WP_Post $post ) {
    return [
        'id'        => (int) $post->ID,
        'title'     => $post->post_title,
        'slug'      => $post->post_name,
        'status'    => $post->post_status,
        'excerpt'   => $post->post_excerpt,
        'order'     => (int) $post->menu_order,
        'permalink' => get_permalink( $post ),
        'edit_url'  => get_edit_post_link( $post->ID, 'raw' ),
        'modified'  => mysql2date( get_option( 'date_format' ), $post->post_modified ),
    ];
}

function snn_builder_lesson_node( WP_Post $post ) {
    $keys      = snn_learn_lesson_keys();
    $subtitles = get_post_meta( $post->ID, $keys['subtitles'], true );
    $ai        = snn_builder_lesson_ai_fields();
    $ai_done   = 0;

    foreach ( $ai as $field ) {
        $value = get_post_meta( $post->ID, $field['slug'], true );
        if ( '' !== $value && [] !== $value && null !== $value ) {
            $ai_done++;
        }
    }

    return snn_builder_base_node( $post ) + [
        'role'         => 'lesson',
        'has_video'    => '' !== (string) get_post_meta( $post->ID, $keys['video'], true ),
        'subtitles'    => is_array( $subtitles ) ? count( $subtitles ) : ( '' !== (string) $subtitles ? 1 : 0 ),
        'duration'     => snn_learn_lesson_duration( $post->ID ),
        'free_preview' => (bool) get_post_meta( $post->ID, $keys['free_preview'], true ),
        'ai_done'      => $ai_done,
        'ai_total'     => count( $ai ),
    ];
}

function snn_builder_course_summary( WP_Post $course ) {
    $structure = snn_learn_course_structure( $course->ID );

    return snn_builder_base_node( $course ) + [
        'role'          => 'course',
        'thumb'         => get_the_post_thumbnail_url( $course, 'medium' ) ?: '',
        'chapter_count' => $structure['chapter_count'],
        'lesson_count'  => $structure['lesson_count'],
        'duration'      => $structure['duration'],
    ];
}

/** The full tree of one course, every builder status included. */
function snn_builder_course_tree( WP_Post $course ) {
    $chapters = snn_builder_children( $course->ID );
    $lessons  = snn_builder_children( wp_list_pluck( $chapters, 'ID' ) );

    $by_chapter = [];
    foreach ( $lessons as $lesson ) {
        $by_chapter[ $lesson->post_parent ][] = $lesson;
    }

    // Anything hanging below a lesson is outside the structure and invisible
    // to learners — count it so the builder can say so.
    $too_deep = count( snn_builder_children( wp_list_pluck( $lessons, 'ID' ) ) );

    $node = snn_builder_course_summary( $course ) + [
        'chapters' => [],
        'too_deep' => $too_deep,
    ];

    foreach ( $chapters as $chapter ) {
        $node['chapters'][] = snn_builder_base_node( $chapter ) + [
            'role'    => 'chapter',
            'lessons' => array_map( 'snn_builder_lesson_node', $by_chapter[ $chapter->ID ] ?? [] ),
        ];
    }

    return $node;
}

/** A node in whatever shape its role uses. */
function snn_builder_node( WP_Post $post ) {
    switch ( snn_learn_post_role( $post ) ) {
        case 'lesson':
            return snn_builder_lesson_node( $post );
        case 'chapter':
            return snn_builder_base_node( $post ) + [
                'role'    => 'chapter',
                'lessons' => array_map( 'snn_builder_lesson_node', snn_builder_children( $post->ID ) ),
            ];
        default:
            return snn_builder_course_summary( $post );
    }
}

